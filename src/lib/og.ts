import { site } from '$lib/site';

function escapeXml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

/** CJK / full-width chars are twice as wide as latin chars. */
function charWidth(ch: string): number {
  return /[\u3400-\u9fff\u4e00-\u9fff\uf900-\ufaff\u3000-\u303f\uff00-\uffef]/.test(ch) ? 2 : 1;
}

/** Wraps a title into at most 3 display lines, truncating with an ellipsis. */
export function wrapTitle(text: string, maxWidth = 44): string[] {
  const maxLines = 3;
  const lines: string[] = [];
  let line = '';
  let width = 0;
  let truncated = false;

  for (const ch of text) {
    const w = charWidth(ch);
    if (width + w > maxWidth && line) {
      lines.push(line);
      if (lines.length >= maxLines) {
        truncated = true;
        break;
      }
      line = ch;
      width = w;
    } else {
      line += ch;
      width += w;
    }
  }
  if (line) lines.push(line);

  if (truncated && lines.length > 0 && lines[lines.length - 1].length > 1) {
    lines[lines.length - 1] = lines[lines.length - 1].slice(0, -1) + '…';
  }
  return lines;
}

